# frozen_string_literal: true

module Patches
  module RubyLLM
    module ProviderPatch
      def complete(messages, ...)
        super(with_draw_image_context(messages), ...)
      end

      def speak(input, model:, voice: nil, **options)
        payload = render_speech_payload(input, model:, voice:, **options)
        response = @connection.post(speech_url(model:), payload)
        parse_speech_response(response, model:).with_response_format(payload[:response_format]).normalized
      end

      private

      def supports_image_tool_results?
        false
      end

      def with_draw_image_context(messages)
        return messages if supports_image_tool_results? || messages.none? { |message| draw_image_result?(message) }

        messages.chunk_while { |left, right| left.role == :tool && right.role == :tool }.flat_map do |group|
          image_context = []
          results = group.map do |message|
            next message unless draw_image_result?(message)

            result = message.content
            content = ::RubyLLM::Content.new("Image generated by the drawing tool. #{result.text}", result.attachments)
            image_context << ::RubyLLM::Message.new(role: :user, content:)
            message.dup.tap { |copy| copy.content = result.text }
          end

          results + image_context
        end
      end

      def draw_image_result?(message)
        message.role == :tool && message.content.is_a?(::AI::DrawResult)
      end

      def speech_url(model: nil)
        raise NotImplementedError, "#{self.class.name} does not support speech generation"
      end

      def render_speech_payload(...)
        raise NotImplementedError, "#{self.class.name} does not support speech generation"
      end

      def parse_speech_response(...)
        raise NotImplementedError, "#{self.class.name} does not support speech generation"
      end
    end
  end
end
